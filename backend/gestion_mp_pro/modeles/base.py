"""Base déclarative, convention de nommage, colonnes communes (MODELE-DONNEES § 1.2).

- Tout défaut est **aussi** un défaut serveur (`colonne(..., defaut=…)`) : une insertion SQL
  hors ORM (reprise, outils) obtient les mêmes valeurs (incohérence 28 de Gestion MP). Un
  instant par défaut vaut `horloge.maintenant()` côté ORM (horloge figée des essais) et
  `now()` côté serveur.
- Clés étrangères `RESTRICT` par défaut (`fk(...)`) ; `CASCADE` seulement pour les lignes d'un
  document.
- `version` : verrou optimiste (`version_id_col`) : tout `UPDATE` par l'ORM vérifie et incrémente.
- Relations `lazy="raise"` : tout chargement est explicite (`selectinload`, `joinedload`).
- `completer_le_schema` pose, sur chaque table, le CHECK des colonnes énumérées
  (`ck_<table>_<colonne>_enum`) et le refus de `NaN` des colonnes `NUMERIC`
  (`ck_<table>_<colonne>_nombre`).
"""

from __future__ import annotations

from datetime import datetime
from decimal import Decimal
from enum import StrEnum
from typing import Any, ClassVar, Final

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    DateTime,
    Enum,
    ForeignKey,
    Identity,
    Index,
    Integer,
    MetaData,
    Numeric,
    String,
    Table,
    Text,
    false,
    func,
    text,
    true,
)
from sqlalchemy.orm import (
    DeclarativeBase,
    Mapped,
    MappedColumn,
    declared_attr,
    mapped_column,
    relationship,
)
from sqlalchemy.sql.elements import ColumnElement, TextClause

from gestion_mp_pro.services import horloge

CONVENTION: Final = {
    "pk": "pk_%(table_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
}
"""Convention de nommage des contraintes (MODELE-DONNEES § 1.2)."""


class Base(DeclarativeBase):
    """La base de toutes les tables ; `__activite__` marque une table d'activité.

    Une table d'activité se vide avec l'activité (`outils/vider_activite.py` de la reprise
    dérive sa liste des modèles, incohérence 32) ; les autres sont des référentiels ou des
    tables gardées (comptes, journal, réglages).
    """

    metadata = MetaData(naming_convention=CONVENTION)
    __activite__: ClassVar[bool] = False


class _Maintenant:
    """Marque « l'instant présent » comme défaut (ORM : horloge de l'usine ; serveur : now())."""

    def __repr__(self) -> str:
        return "MAINTENANT"


MAINTENANT: Final = _Maintenant()
_SANS: Final = object()


def defauts(valeur: object) -> tuple[object, ColumnElement[Any] | TextClause | str]:
    """Le défaut ORM et le défaut serveur qui lui correspond, pour une même valeur."""
    if valeur is MAINTENANT:
        return horloge.maintenant, func.now()
    if isinstance(valeur, bool):
        return valeur, true() if valeur else false()
    if isinstance(valeur, StrEnum):
        return valeur, valeur.value
    if isinstance(valeur, str):
        return valeur, valeur
    if isinstance(valeur, int | Decimal):
        return valeur, text(str(valeur))
    raise TypeError(f"défaut non pris en charge : {valeur!r}")


def colonne(*args: Any, defaut: object = _SANS, **kw: Any) -> MappedColumn[Any]:
    """`mapped_column` dont le défaut vaut des deux côtés (ORM et serveur)."""
    if defaut is not _SANS:
        kw["default"], kw["server_default"] = defauts(defaut)
    return mapped_column(*args, **kw)


def fk(cible: str, ondelete: str = "RESTRICT", **kw: Any) -> ForeignKey:
    """Une clé étrangère ; `RESTRICT` sauf mention (rien ne disparaît en silence)."""
    return ForeignKey(cible, ondelete=ondelete, **kw)


def cle_primaire() -> MappedColumn[int]:
    """`INTEGER GENERATED BY DEFAULT AS IDENTITY` : la reprise garde les ids de Gestion MP."""
    return mapped_column(Integer, Identity(always=False), primary_key=True, sort_order=-1)


def cle_primaire_longue() -> MappedColumn[int]:
    """`BIGINT GENERATED BY DEFAULT AS IDENTITY` (mouvement, journal, notification)."""
    return mapped_column(BigInteger, Identity(always=False), primary_key=True, sort_order=-1)


def chaine(longueur: int, defaut: str = "") -> MappedColumn[str]:
    """Un texte borné, vide par défaut."""
    return colonne(String(longueur), defaut=defaut)


def instant(defaut: object = _SANS) -> MappedColumn[Any]:
    """Un instant (`TIMESTAMPTZ`)."""
    return colonne(DateTime(timezone=True), defaut=defaut)


def qui(nullable: bool = True, **kw: Any) -> MappedColumn[Any]:
    """Une colonne « qui » : clé vers `utilisateur.id` (NULL = système ou inconnu)."""
    return mapped_column(fk("utilisateur.id"), nullable=nullable, **kw)


def recherche() -> MappedColumn[str]:
    """`texte_recherche` : minuscules, sans accents, champs cherchables mis bout à bout.

    Tenue par l'écouteur de `modeles/recherche.py` ; index GIN trigrammes (`index_recherche`).
    """
    return colonne(Text, defaut="")


def index_recherche() -> Index:
    """L'index GIN `gin_trgm_ops` de `texte_recherche` (recherche « tous les mots »)."""
    return Index(
        None,
        "texte_recherche",
        postgresql_using="gin",
        postgresql_ops={"texte_recherche": "gin_trgm_ops"},
    )


def enfants(cible: str, ordre: str | None = None) -> Any:
    """Les lignes d'un document (`ON DELETE CASCADE` en base) : chargement explicite seulement.

    `ordre` : colonne de tri de la collection (par défaut l'`id` de la ligne).
    """
    return relationship(
        cible,
        lazy="raise",
        cascade="all, delete-orphan",
        passive_deletes=True,
        order_by=f"{cible}.{ordre or 'id'}",
    )


def vers(cible: str, **kw: Any) -> Any:
    """Une relation plusieurs-à-un, en lecture seule, chargée explicitement."""
    return relationship(cible, lazy="raise", viewonly=True, **kw)


class AvecVersion:
    """Colonne `version` : verrou optimiste des documents et fiches modifiables."""

    version: Mapped[int] = colonne(Integer, defaut=1)

    @declared_attr.directive
    def __mapper_args__(cls) -> dict[str, Any]:
        """`version_id_col` : l'ORM vérifie et incrémente `version` à chaque mise à jour."""
        return {"version_id_col": cls.__table__.c.version}  # type: ignore[attr-defined]


class AvecCreation:
    """`cree_le` : l'instant de création."""

    cree_le: Mapped[datetime] = instant(defaut=MAINTENANT)


class AvecModification:
    """`modifie_le` (posé par l'ORM à chaque mise à jour) et `modifie_par_id`."""

    modifie_le: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), onupdate=horloge.maintenant
    )
    modifie_par_id: Mapped[int | None] = qui()


def _valeurs(type_: Enum) -> str:
    """La liste SQL des valeurs d'une énumération : `'a', 'b'`."""
    return ", ".join("'" + v.replace("'", "''") + "'" for v in type_.enums)


def completer_le_schema(metadata: MetaData) -> None:
    """Pose les CHECK génériques (valeurs des énumérations, refus de NaN) ; rejouable."""
    for table in metadata.tables.values():
        _completer_table(table)


def _completer_table(table: Table) -> None:
    """Les CHECK génériques d'une table."""
    noms = {c.name for c in table.constraints if isinstance(c, CheckConstraint)}
    for col in table.columns:
        if isinstance(col.type, Enum):
            nom, regle = f"{col.name}_enum", f"{col.name} IN ({_valeurs(col.type)})"
        elif isinstance(col.type, Numeric) and col.computed is None:
            nom, regle = f"{col.name}_nombre", f"{col.name} <> 'NaN'"
        else:
            continue
        if f"ck_{table.name}_{nom}" not in noms and nom not in noms:
            table.append_constraint(CheckConstraint(regle, name=nom))
